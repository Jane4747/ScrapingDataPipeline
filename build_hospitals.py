def split_zj(s):
    if "三级甲等" in s:
        grade = "三级甲等" if "标准" not in s else "三级甲等(标准)"
    elif "三级乙等" in s:
        grade = "三级乙等"
    else:
        grade = "三级"
    cat = (s.replace("三级甲等", "").replace("三级乙等", "")
            .replace("三级", "").replace("标准", "").strip())
    return grade, cat

